// Map original pricing string template (from proxies.ts) to localized string
export function getLocalizedPricing(pricing: string, locale: Locale): string {
  if (locale === "en") return pricing;

  // Patterns
  // 1. "From $X/GB"
  if (pricing.startsWith("From $") && pricing.endsWith("/GB")) {
    const val = pricing.slice(6, -3);
    const m: Record<Locale, string> = {
      en: pricing,
      zh: `起自 $${val}/GB`,
      ru: `От $${val}/ГБ`,
      ja: `$${val}/GB から`,
      fr: `À partir de $${val}/Go`,
      de: `Ab $${val}/GB`,
    };
    return m[locale] || pricing;
  }

  // 2. "From $X/mo"
  if (pricing.startsWith("From $") && pricing.endsWith("/mo")) {
    const val = pricing.slice(6, -3);
    const m: Record<Locale, string> = {
      en: pricing,
      zh: `$${val}/月 起`,
      ru: `От $${val}/мес.`,
      ja: `$${val}/月 から`,
      fr: `À partir de $${val}/mois`,
      de: `Ab $${val}/Monat`,
    };
    return m[locale] || pricing;
  }

  // 3. "From $X/IP"
  if (pricing.startsWith("From $") && pricing.endsWith("/IP")) {
    const val = pricing.slice(6, -3);
    const m: Record<Locale, string> = {
      en: pricing,
      zh: `$${val}/IP 起`,
      ru: `От $${val}/IP`,
      ja: `$${val}/IP から`,
      fr: `À partir de $${val}/IP`,
      de: `Ab $${val}/IP`,
    };
    return m[locale] || pricing;
  }

  // 4. "From $X/day"
  if (pricing.startsWith("From $") && pricing.endsWith("/day")) {
    const val = pricing.slice(6, -4);
    const m: Record<Locale, string> = {
      en: pricing,
      zh: `$${val}/天 起`,
      ru: `От $${val}/день`,
      ja: `$${val}/日 から`,
      fr: `À partir de $${val}/jour`,
      de: `Ab $${val}/Tag`,
    };
    return m[locale] || pricing;
  }

  // Exact matches
  const exact: Record<string, Record<Locale, string>> = {
    "Free tier available": {
      en: "Free tier available",
      zh: "提供免费套餐",
      ru: "Доступен бесплатный тариф",
      ja: "無料プランあり",
      fr: "Offre gratuite disponible",
      de: "Kostenloser Tarif verfügbar",
    },
    "Custom pricing": {
      en: "Custom pricing",
      zh: "定制价格",
      ru: "Индивидуальный тариф",
      ja: "カスタム料金",
      fr: "Tarif personnalisé",
      de: "Individuelle Preise",
    },
    "Free lists + Premium": {
      en: "Free lists + Premium",
      zh: "免费列表 + 付费版",
      ru: "Бесплатные списки + Премиум",
      ja: "無料リスト + プレミアム",
      fr: "Listes gratuites + Premium",
      de: "Kostenlose Listen + Premium",
    },
    "Free / $5/mo": {
      en: "Free / $5/mo",
      zh: "免费 / $5/月",
      ru: "Бесплатно / $5/мес.",
      ja: "無料 / $5/月",
      fr: "Gratuit / 5 $/mois",
      de: "Kostenlos / $5/Monat",
    },
  };

  return exact[pricing]?.[locale] || pricing;
}

