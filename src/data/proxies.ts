// Helper functions
export function getProxyProvidersByRegion(region: Region): ProxyProvider[] {
  return proxyProviders.filter((p) => p.region === region);
}

export function getProxyProvidersByType(type: ProxyType): ProxyProvider[] {
  return proxyProviders.filter((p) => p.types.includes(type));
}

export function getProxyProvidersSorted(
  providers: ProxyProvider[],
  sort: "rating" | "price" | "name"
): ProxyProvider[] {
  return [...providers].sort((a, b) => {
    if (sort === "rating") return b.rating - a.rating;
    if (sort === "name") return a.name.localeCompare(b.name);
    // price: extract number from pricing string
    const priceA = parseFloat(a.pricing.replace(/[^0-9.]/g, "")) || 999;
    const priceB = parseFloat(b.pricing.replace(/[^0-9.]/g, "")) || 999;
    return priceA - priceB;
  });
}

